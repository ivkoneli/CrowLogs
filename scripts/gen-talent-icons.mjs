// Generates src/lib/talentIcons.js — a static Legion talent-icon table:
//   { ClassName: { SpecName: [ [icon, icon, icon] x7 rows ] } }   (icon = name, '' if none)
// Built from wago.tools DB2 data (Talent, ChrSpecialization, SpellMisc) + the icon
// listfile. Run once: `node scripts/gen-talent-icons.mjs`. Re-run to refresh.
import { writeFileSync } from 'node:fs'

const BUILD = '7.3.5.26972'
const CLASS_BY_ID = {
  1: 'Warrior', 2: 'Paladin', 3: 'Hunter', 4: 'Rogue', 5: 'Priest', 6: 'Death Knight',
  7: 'Shaman', 8: 'Mage', 9: 'Warlock', 10: 'Monk', 11: 'Druid', 12: 'Demon Hunter',
}

async function csv(table) {
  const r = await fetch(`https://wago.tools/db2/${table}/csv?build=${BUILD}`)
  if (!r.ok) throw new Error(`${table}: HTTP ${r.status}`)
  return await r.text()
}
// Quote-aware CSV → array of field-objects keyed by header.
function parseCsv(text) {
  const lines = text.split('\n').filter((l) => l.length)
  const header = splitCsv(lines[0])
  return lines.slice(1).map((l) => {
    const f = splitCsv(l)
    const o = {}
    header.forEach((h, i) => (o[h] = f[i]))
    return o
  })
}
function splitCsv(line) {
  const out = []
  let cur = ''
  let q = false
  for (let i = 0; i < line.length; i++) {
    const c = line[i]
    if (c === '"') q = !q
    else if (c === ',' && !q) { out.push(cur); cur = '' }
    else cur += c
  }
  out.push(cur)
  return out
}

console.log('Fetching DB2 tables…')
const [talentRows, specRows, miscText, iconsJson] = await Promise.all([
  csv('Talent').then(parseCsv),
  csv('ChrSpecialization').then(parseCsv),
  csv('SpellMisc'),
  fetch('https://wago.tools/api/files?search=interface/icons/').then((r) => r.json()),
])

// SpellID -> icon name. SpellMisc is large; parse minimally (all numeric, no quoted text).
const miscLines = miscText.split('\n')
const mh = miscLines[0].split(',')
const iIcon = mh.indexOf('SpellIconFileDataID')
const iSpell = mh.indexOf('SpellID')
const spellIcon = new Map() // spellID -> fileDataID
for (let k = 1; k < miscLines.length; k++) {
  const f = miscLines[k].split(',')
  const sid = f[iSpell]
  if (sid && !spellIcon.has(sid)) spellIcon.set(sid, f[iIcon])
}
// fileDataID -> icon name (strip path + extension)
const fdidName = new Map()
for (const [fdid, path] of Object.entries(iconsJson)) {
  fdidName.set(fdid, path.replace(/^interface\/icons\//i, '').replace(/\.blp$/i, ''))
}
const iconForSpell = (spellId) => {
  const fdid = spellIcon.get(String(spellId))
  return (fdid && fdidName.get(String(fdid))) || ''
}

// specID -> { class, name }  (player specs only)
const specInfo = new Map()
for (const s of specRows) {
  const cls = CLASS_BY_ID[+s.ClassID]
  if (!cls || !s.Name_lang) continue
  specInfo.set(s.ID, { class: cls, name: s.Name_lang })
}

// Talents grouped by class: list of { specID, tier, col, spellID }.
const byClass = new Map()
// talentID -> { row, col, icon }. The CrowLogsHelper addon stores GetTalentInfo's
// talentID per tier, so this lets the site resolve a Lua snapshot to exact icons
// without the armory's column-packed build hash. The talent's ID encodes its tier+col.
const byTalentId = {}
for (const t of talentRows) {
  const cls = CLASS_BY_ID[+t.ClassID]
  if (!cls) continue
  ;(byClass.get(cls) || byClass.set(cls, []).get(cls)).push({
    specID: t.SpecID, tier: +t.TierID, col: +t.ColumnIndex, spellID: t.SpellID,
  })
  if (t.ID && byTalentId[t.ID] === undefined) {
    byTalentId[t.ID] = { row: +t.TierID + 1, col: +t.ColumnIndex + 1, icon: iconForSpell(t.SpellID) || '' }
  }
}

// Build { class: { spec: [ [icon,icon,icon] x7 ] } }. A cell prefers the spec-specific
// talent, else the class-wide one (SpecID 0).
const out = {}
let cells = 0
let missing = 0
for (const [specID, info] of specInfo) {
  const list = byClass.get(info.class) || []
  const grid = Array.from({ length: 7 }, () => ['', '', ''])
  for (let tier = 0; tier < 7; tier++) {
    for (let col = 0; col < 3; col++) {
      const cands = list.filter((x) => x.tier === tier && x.col === col)
      const pick = cands.find((x) => x.specID === specID) || cands.find((x) => x.specID === '0') || cands[0]
      if (pick) {
        const icon = iconForSpell(pick.spellID)
        grid[tier][col] = icon
        cells++
        if (!icon) missing++
      }
    }
  }
  ;(out[info.class] = out[info.class] || {})[info.name] = grid
}

const banner = `// AUTO-GENERATED by scripts/gen-talent-icons.mjs from wago.tools (build ${BUILD}).\n// Legion 7x3 talents: ClassName -> SpecName -> [ [icon,icon,icon] x7 rows ] (icon name, '' = none).\n// TALENT_BY_ID maps a GetTalentInfo talentID (what CrowLogsHelper stores) -> { row, col, icon }.\n`
writeFileSync(
  'src/lib/talentIcons.js',
  `${banner}export const TALENT_ICONS = ${JSON.stringify(out)}\nexport const TALENT_BY_ID = ${JSON.stringify(byTalentId)}\n`,
)

const classes = Object.keys(out)
console.log(`\nWrote src/lib/talentIcons.js`)
console.log(`classes: ${classes.length}, specs: ${classes.reduce((n, c) => n + Object.keys(out[c]).length, 0)}`)
console.log(`talent cells filled: ${cells}, missing icon: ${missing}`)
console.log(`talentIDs mapped: ${Object.keys(byTalentId).length}`)
console.log('sample Warrior/Arms row1:', out.Warrior?.Arms?.[0])
