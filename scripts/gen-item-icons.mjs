// Generates src/lib/itemIcons.js — a static trinket lookup:
//   { itemID: { name, icon, ilvl, quality } }   (icon = name, quality = string)
// Built from wago.tools DB2 (Item for icon+slot, ItemSparse for name/ilvl/quality) +
// the icon listfile. The CrowLogsHelper addon snapshots only an item's id per slot
// (slots 13/14 = trinkets), so the site resolves the icon/name from this table without
// any runtime armory/Wowhead call. Run once: `node scripts/gen-item-icons.mjs`.
//
// Scoped to InventoryType 12 (trinkets) — that's all the meter renders from the Lua
// snapshot; full gear still comes from the armory cache (Lua-first, armory-fallback).
import { writeFileSync } from 'node:fs'

const BUILD = '7.3.5.26972'
const TRINKET_INVTYPE = 12
const QUALITY = { 0: 'common', 1: 'common', 2: 'uncommon', 3: 'rare', 4: 'epic', 5: 'legendary', 6: 'artifact', 7: 'heirloom' }

async function csv(table) {
  const r = await fetch(`https://wago.tools/db2/${table}/csv?build=${BUILD}`)
  if (!r.ok) throw new Error(`${table}: HTTP ${r.status}`)
  return await r.text()
}
// Quote-aware CSV → array of field-objects keyed by header.
function parseCsv(text) {
  const lines = text.split('\n').filter((l) => l.length)
  const header = splitCsv(lines[0])
  return lines.slice(1).map((l) => {
    const f = splitCsv(l)
    const o = {}
    header.forEach((h, i) => (o[h] = f[i]))
    return o
  })
}
function splitCsv(line) {
  const out = []
  let cur = ''
  let q = false
  for (let i = 0; i < line.length; i++) {
    const c = line[i]
    if (c === '"') q = !q
    else if (c === ',' && !q) { out.push(cur); cur = '' }
    else cur += c
  }
  out.push(cur)
  return out
}

console.log('Fetching DB2 tables…')
const [itemRows, sparseRows, iconsJson] = await Promise.all([
  csv('Item').then(parseCsv),
  csv('ItemSparse').then(parseCsv),
  fetch('https://wago.tools/api/files?search=interface/icons/').then((r) => r.json()),
])

// fileDataID -> icon name (strip path + extension), reused from the talent generator.
const fdidName = new Map()
for (const [fdid, path] of Object.entries(iconsJson)) {
  fdidName.set(fdid, path.replace(/^interface\/icons\//i, '').replace(/\.blp$/i, ''))
}

// itemID -> icon name (Item.IconFileDataID -> listfile).
const itemIcon = new Map()
for (const it of itemRows) {
  const name = fdidName.get(String(it.IconFileDataID))
  if (name) itemIcon.set(it.ID, name)
}

// Emit trinkets only: { id: { name, icon, ilvl, quality } }.
const out = {}
let withIcon = 0
for (const s of sparseRows) {
  if (+s.InventoryType !== TRINKET_INVTYPE) continue
  const name = (s.Display_lang || '').trim()
  if (!name) continue
  const icon = itemIcon.get(s.ID) || ''
  if (icon) withIcon++
  out[s.ID] = {
    name,
    icon,
    ilvl: +s.ItemLevel || 0,
    quality: QUALITY[+s.OverallQualityID] || 'common',
  }
}

const banner = `// AUTO-GENERATED by scripts/gen-item-icons.mjs from wago.tools (build ${BUILD}).\n// Trinkets (InventoryType 12): itemID -> { name, icon (name), ilvl, quality }.\n`
writeFileSync('src/lib/itemIcons.js', `${banner}export const ITEM_ICONS = ${JSON.stringify(out)}\n`)

const total = Object.keys(out).length
console.log(`\nWrote src/lib/itemIcons.js`)
console.log(`trinkets: ${total}, with icon: ${withIcon}, missing icon: ${total - withIcon}`)
console.log('sample 128024:', out['128024'])
